import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { sourceManifestPaths } from "./manifest-inventory.mjs";

const root = process.cwd();

const full = await readJson("generated/storage-layout/FullMarketVaultV1.json");
const clone = await readJson(
  "generated/storage-layout/CloneMarketVaultV1.json",
);
const normalizedFull = stripPresentationFields(full);
const normalizedClone = stripPresentationFields(clone);
assert(
  JSON.stringify(normalizedFull) === JSON.stringify(normalizedClone),
  "Full and Clone storage layouts differ",
);
assert(full.storage.length > 0, "storage layout is empty");

const selectors = await readJson("generated/registries/selectors.json");
const selectorKeys = new Set();
for (const item of selectors) {
  assert(
    /^0x[0-9a-f]{8}$/.test(item.selector),
    `invalid selector for ${item.signature}`,
  );
  const key = `${item.contract}:${item.signature}`;
  assert(!selectorKeys.has(key), `duplicate selector entry ${key}`);
  selectorKeys.add(key);
}
assert(selectors.length > 0, "selector registry is empty");

const bytecode = await readJson("generated/registries/bytecode.json");
for (const contract of ["FullMarketVaultV1", "CloneMarketVaultV1"]) {
  const entry = bytecode.find((item) => item.contract === contract);
  assert(entry, `missing bytecode entry for ${contract}`);
  assert(entry.runtimeBytes < 23 * 1024, `${contract} runtime exceeds 23 KiB`);
}

const manifest = await readJson("manifests/source-manifest.json");
assert(manifest.schemaVersion === 1, "unsupported source manifest schema");
assert(manifest.compiler === "0.8.36", "source manifest compiler drift");
assert(manifest.evmVersion === "cancun", "source manifest EVM-version drift");
assert(
  JSON.stringify(manifest.optimizer) ===
    JSON.stringify({ enabled: true, runs: 200, viaIR: true }),
  "source manifest optimizer drift",
);
assert(
  JSON.stringify(manifest.metadata) ===
    JSON.stringify({ bytecodeHash: "none", cborMetadata: false }),
  "source manifest metadata drift",
);
assert(
  Array.isArray(manifest.files) && manifest.files.length > 0,
  "source manifest files are empty",
);

const expectedPaths = await sourceManifestPaths(root);
const actualPaths = manifest.files.map((entry) => entry.path);
assert(
  new Set(actualPaths).size === actualPaths.length,
  "source manifest contains duplicate paths",
);
assert(
  JSON.stringify(actualPaths) === JSON.stringify(expectedPaths),
  `source manifest path inventory is stale; regenerate artifacts\nexpected: ${JSON.stringify(expectedPaths)}\nactual: ${JSON.stringify(actualPaths)}`,
);
for (const entry of manifest.files) {
  assert(
    /^[0-9a-f]{64}$/.test(entry.sha256),
    `invalid source manifest hash for ${entry.path}`,
  );
  const actual = sha256(await readFile(join(root, entry.path)));
  assert(
    actual === entry.sha256,
    `source manifest hash is stale for ${entry.path}`,
  );
}
assert(
  JSON.stringify(manifest.bytecode) === JSON.stringify(bytecode),
  "source manifest bytecode does not match generated bytecode registry",
);

console.log(
  `generated artifacts valid: ${full.storage.length} storage entries, ${selectors.length} selectors, ${manifest.files.length} hashed files`,
);

function stripPresentationFields(value) {
  if (Array.isArray(value)) return value.map(stripPresentationFields);
  if (value !== null && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([key]) => key !== "contract")
        .map(([key, child]) => [key, stripPresentationFields(child)]),
    );
  }
  return value;
}

async function readJson(path) {
  return JSON.parse(await readFile(path, "utf8"));
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}
